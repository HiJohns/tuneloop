import fs from 'node:fs'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const SOURCE = path.join(ROOT, 'src/pages/Checkout.jsx')
const DEFECT = path.join(ROOT, 'src/pages/CheckoutAuditDefect.jsx')
const VITEST = path.join(ROOT, 'node_modules/vitest/vitest.mjs')

function writeDefectCopy() {
  const src = fs.readFileSync(SOURCE, 'utf8')
  const start = src.indexOf('{pricingV2.tiers.map((tier, i) => {')
  if (start < 0) throw new Error('tier block not found — Checkout source changed')
  const end = src.indexOf('})}', start) + 3
  const block = src.slice(start, end)
    .replace('map((tier, i)', 'map((t, i)')
    .replace(/\btier\./g, 't.')
  const out = `/* eslint-disable */\n// Generated by scripts/page-smoke/run-defect.mjs for the #2298 red-green proof. Do not commit.\n` + src.slice(0, start) + block + src.slice(end)
  fs.writeFileSync(DEFECT, out)
}

writeDefectCopy()
let status = 1
try {
  const result = spawnSync(process.execPath, [VITEST, 'run', '--config', 'vitest.defect.config.js'], {
    cwd: ROOT,
    stdio: 'inherit',
  })
  status = result.status ?? 1
} finally {
  try { fs.unlinkSync(DEFECT) } catch {}
}
process.exit(status)
